// OpenAPI Generator entry point: `generate` rewrites the committed TypeScript clients from the contracts in
// contracts/, `check` fails when the committed clients differ from a fresh generation. The generator version is
// pinned in openapitools.json. Generated code is never edited by hand. No relative imports, so it runs through
// Node type stripping (see package.json scripts) and through the tsc build.
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..", "..");
const GENERATOR = "typescript-fetch";
// One entry per contract. Add the Test Management and TDM contracts here to follow the same pattern.
const CLIENTS = [
  {
    spec: join(root, "contracts", "synthetic-api.openapi.json"),
    out: join(root, "src", "generated", "synthetic-api"),
  },
];
// The generator targets browser lib types and a looser tsconfig than this repo's strict one, so each generated file
// opts out of type checking; the typed client surface it exports is still checked at every call site.
const GENERATED_HEADER =
  "// @ts-nocheck -- generated by OpenAPI Generator (strict-mode mismatch); regenerate with npm run generate, never edit\n";
// Generator bookkeeping that is not part of the client and changes with the generator, not the contract.
const GENERATOR_BOOKKEEPING = [
  ".openapi-generator",
  ".openapi-generator-ignore",
];

function generateInto(spec: string, outputDir: string): void {
  execFileSync(
    join(root, "node_modules", ".bin", "openapi-generator-cli"),
    [
      "generate",
      "--generator-name",
      GENERATOR,
      "--input-spec",
      spec,
      "--output",
      outputDir,
      "--global-property",
      "apis,models,supportingFiles",
      "--additional-properties",
      "supportsES6=true,importFileExtension=.js",
    ],
    { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
  );
  for (const entry of GENERATOR_BOOKKEEPING) {
    rmSync(join(outputDir, entry), { recursive: true, force: true });
  }
  for (const file of listFiles(outputDir).filter((f) => f.endsWith(".ts"))) {
    const path = join(outputDir, file);
    writeFileSync(path, GENERATED_HEADER + readFileSync(path, "utf8"));
  }
}

function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath, entry.name)))
    .sort();
}

function differences(expectedDir: string, actualDir: string): string[] {
  const expected = listFiles(expectedDir);
  const actual = listFiles(actualDir);
  const problems = [
    ...expected.filter((f) => !actual.includes(f)).map((f) => `missing: ${f}`),
    ...actual
      .filter((f) => !expected.includes(f))
      .map((f) => `unexpected: ${f}`),
  ];
  for (const file of expected.filter((f) => actual.includes(f))) {
    if (
      readFileSync(join(expectedDir, file), "utf8") !==
      readFileSync(join(actualDir, file), "utf8")
    ) {
      problems.push(`changed: ${file}`);
    }
  }
  return problems;
}

function flag(args: string[], name: string): string | undefined {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
}

function main(argv: string[]): number {
  const [command, ...args] = argv;
  const override = flag(args, command === "check" ? "--against" : "--out");
  for (const client of CLIENTS) {
    const scratch = mkdtempSync(join(tmpdir(), "uaf-generate-"));
    try {
      const target = override ?? client.out;
      if (command === "generate") {
        generateInto(client.spec, scratch);
        rmSync(target, { recursive: true, force: true });
        cpSync(scratch, target, { recursive: true });
        console.log(`generated ${relative(root, target)}`);
      } else if (command === "check") {
        generateInto(client.spec, scratch);
        const problems = differences(scratch, target);
        if (problems.length > 0) {
          console.error(
            `Drift in ${relative(root, target)}; run npm run generate:\n${problems.join("\n")}`,
          );
          return 1;
        }
        console.log(`${relative(root, target)} is up to date`);
      } else {
        console.error(
          "Usage: cli.ts generate [--out dir] | check [--against dir]",
        );
        return 2;
      }
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  }
  return 0;
}

process.exitCode = main(process.argv.slice(2));
